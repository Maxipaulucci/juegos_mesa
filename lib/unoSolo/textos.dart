String reglasUnoSolo() => '''
UNO SOLO

Juego de ingenio con tablero en cruz y fichas. El objetivo es saltar piezas para eliminarlas hasta que quede una sola en el centro.

PREPARACIÓN
· Pon una ficha en cada agujero del tablero.
· Dejá completamente vacío el agujero central.

MOVIMIENTO
· Mové una ficha en forma horizontal o vertical (nunca en diagonal).
· Para mover, saltá por encima de una ficha vecina hacia un agujero libre que esté justo después (a dos casillas).
· Cada vez que saltás una ficha, retírala del tablero.

FIN DEL JUEGO Y PUNTUACIÓN
El objetivo principal es que quede un solo botón exactamente en el centro del tablero.

Según cuántas fichas te sobren al final:
· 5 fichas: Regular
· 4 fichas: Mejor
· 3 fichas: Bueno
· 2 fichas: Muy bueno
· 1 ficha: ¡Perfecto (Ganaste)!

CONTRA OTRA PERSONA
· Se turnan los saltos sobre el mismo tablero.
· Quien logra la ficha única en el centro gana la partida.
''';
